CREATE TABLE table_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_id BIGINT NOT NULL REFERENCES restaurant_table(id),
    status VARCHAR(24) NOT NULL DEFAULT 'OPEN'
        CHECK (status IN ('OPEN', 'CHECKOUT_PENDING', 'CLOSED')),
    opened_by BIGINT NOT NULL REFERENCES staff_user(id),
    opened_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ,
    CHECK ((status = 'CLOSED') = (closed_at IS NOT NULL)),
    CHECK (closed_at IS NULL OR closed_at >= opened_at)
);

-- Checkout is still an active visit. Enforce this even for writers outside the API.
CREATE UNIQUE INDEX table_session_one_active_per_table ON table_session(table_id)
    WHERE status IN ('OPEN', 'CHECKOUT_PENDING');
