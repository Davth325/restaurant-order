CREATE TABLE menu_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL CHECK (length(trim(name)) > 0),
    display_order INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE menu_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL UNIQUE,
    category_id BIGINT NOT NULL REFERENCES menu_category(id),
    name VARCHAR(160) NOT NULL CHECK (length(trim(name)) > 0),
    price_vnd BIGINT NOT NULL CHECK (price_vnd >= 0 AND price_vnd <= 9007199254740991),
    image_path VARCHAR(255) NOT NULL CHECK (image_path LIKE '/menu-images/%'),
    available BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX menu_item_category_idx ON menu_item(category_id);
