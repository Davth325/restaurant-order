CREATE TABLE fulfillment_unit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id BIGINT NOT NULL REFERENCES order_item(id) ON DELETE CASCADE,
    unit_number INTEGER NOT NULL CHECK (unit_number BETWEEN 1 AND 20),
    status VARCHAR(24) NOT NULL DEFAULT 'QUEUED' CHECK (status IN ('QUEUED', 'PREPARING', 'READY')),
    started_at TIMESTAMPTZ,
    started_by BIGINT REFERENCES staff_user(id),
    ready_at TIMESTAMPTZ,
    ready_by BIGINT REFERENCES staff_user(id),
    UNIQUE(order_item_id, unit_number),
    CHECK ((status = 'QUEUED' AND started_at IS NULL AND started_by IS NULL AND ready_at IS NULL AND ready_by IS NULL)
        OR (status = 'PREPARING' AND started_at IS NOT NULL AND started_by IS NOT NULL AND ready_at IS NULL AND ready_by IS NULL)
        OR (status = 'READY' AND started_at IS NOT NULL AND started_by IS NOT NULL AND ready_at IS NOT NULL AND ready_at >= started_at AND ready_by IS NOT NULL))
);
