CREATE TABLE guest_pairing (
    code_hash VARCHAR(64) PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES table_session(id),
    created_by BIGINT NOT NULL REFERENCES staff_user(id),
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ
);
CREATE TABLE guest_device (
    token_hash VARCHAR(64) PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES table_session(id),
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX guest_device_session_idx ON guest_device(session_id);
CREATE TABLE order_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES table_session(id),
    request_key UUID NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    total_vnd BIGINT NOT NULL CHECK (total_vnd BETWEEN 0 AND 9007199254740991),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(session_id, request_key)
);
CREATE TABLE order_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES order_batch(id),
    menu_item_id BIGINT NOT NULL REFERENCES menu_item(id),
    item_name VARCHAR(160) NOT NULL,
    unit_price_vnd BIGINT NOT NULL CHECK (unit_price_vnd BETWEEN 0 AND 9007199254740991),
    quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 20),
    note VARCHAR(300) NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'QUEUED' CHECK (status IN ('QUEUED'))
);
CREATE INDEX order_item_batch_idx ON order_item(batch_id);
